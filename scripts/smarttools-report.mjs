#!/usr/bin/env node
/**
 * scripts/smarttools-report.mjs
 * ═══════════════════════════════════════════════════════════════════════════
 *  Generates docs/smarttools/TRACEABILITY_MATRIX.md from the *actual* state of
 *  the repository: the implemented catalogue (#1–#30 + batches) and the
 *  registered #31–#150 seed. It never invents evidence.
 *
 *  Usage: node scripts/smarttools-report.mjs
 * ═══════════════════════════════════════════════════════════════════════════
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8');

// ── Parse the implemented catalogue (catalog files) ────────────────────────
const catalogFiles = readdirSync(join(ROOT, 'lib/tools'))
  .filter((f) => /^smartToolsCatalog\d*\.ts$/.test(f))
  .sort();
const catalog = [];
for (const f of catalogFiles) {
  const src = read(join('lib/tools', f));
  const re = /toolId: '([^']+)'[\s\S]*?slug: '([^']+)'[\s\S]*?order: (\d+)[\s\S]*?titleEn: '([^']+)'[\s\S]*?titleAr: '([^']+)'[\s\S]*?componentPath: '([^']+)'[\s\S]*?enginePath: '([^']+)'[\s\S]*?schemaPath: '([^']+)'/g;
  let m;
  while ((m = re.exec(src))) {
    catalog.push({
      toolId: m[1], slug: m[2], order: Number(m[3]), titleEn: m[4], titleAr: m[5],
      componentPath: m[6], enginePath: m[7], schemaPath: m[8],
    });
  }
}
catalog.sort((a, b) => a.order - b.order);

// ── Parse the #31–#150 registry seed ───────────────────────────────────────
const regSrc = read('lib/tools/toolRegistry150.ts');
const regRe = /\[(\d+), '([^']+)', '([^']+)', '([^']+)', '([^']+)', '([^']+)', (true|false)\]/g;
const registered = [];
let rm;
while ((rm = regRe.exec(regSrc))) {
  registered.push({
    id: Number(rm[1]),
    category: rm[2],
    slug: rm[3],
    titleEn: rm[4],
    restricted: rm[7] === 'true',
  });
}
const implementedMatch = regSrc.match(/IMPLEMENTED_TOOL_IDS: readonly number\[\] = \[([^\]]*)\]/);
const implemented = new Set(
  (implementedMatch?.[1] ?? '')
    .split(',')
    .map((x) => Number(x.trim()))
    .filter((n) => Number.isFinite(n) && n > 0)
);

function fileStatus(relPath, ext) {
  return existsSync(join(ROOT, relPath + ext)) ? 'yes' : 'NO';
}

const lines = [];
lines.push('# SmartTools — Traceability & Acceptance Matrix');
lines.push('');
lines.push('> Generated by `node scripts/smarttools-report.mjs`. Do not hand-edit.');
lines.push('> Ledger vocabulary: **PASS / PARTIAL / FAIL / NOT RUN / BLOCKED**.');
lines.push('');
lines.push('## Summary');
lines.push('');
lines.push(`- Implemented catalogue entries: **${catalog.length}**`);
lines.push(`- Registered tools #31–#150: **${registered.length}**`);
lines.push(`- Marked implemented in registry seed: **${implemented.size}** (${[...implemented].sort((a, b) => a - b).join(', ') || 'none'})`);
lines.push(`- Total tool identities tracked: **${catalog.length - implemented.size + registered.length}** (#1-#30 legacy + #31-#150 registered)`);
lines.push('');
lines.push('## Implemented tools (catalogue) — functional evidence');
lines.push('');
lines.push('| Tool | Slug | Engine | Schema | Component | Route | Test | Status |');
lines.push('|---|---|---|---|---|---|---|---|');
for (const t of catalog) {
  const engine = existsSync(join(ROOT, t.enginePath + '.ts')) ? 'yes' : 'NO';
  const schema = existsSync(join(ROOT, t.schemaPath + '.ts')) ? 'yes' : 'NO';
  const component = existsSync(join(ROOT, t.componentPath.replace(/^@\//, '') + '.tsx')) ? 'yes' : 'NO';
  const route = fileStatus(`app/smarttools/${t.slug}/page`, '.tsx');
  const test = existsSync(join(ROOT, t.enginePath + '.test.ts')) ? 'yes' : 'NO';
  lines.push(
    `| ${t.titleEn} | \`${t.slug}\` | ${engine} | ${schema} | ${component} | ${route} | ${test} | ${
      [engine, schema, component, route].every((x) => x === 'yes') ? 'PASS' : 'PARTIAL'
    } |`
  );
}
lines.push('');
lines.push('## Registered tools #31–#150 — development status');
lines.push('');
lines.push('| ID | Category | Slug | Development | Availability | Restricted | Status |');
lines.push('|---|---|---|---|---|---|---|');
for (const t of registered) {
  const isImpl = implemented.has(t.id);
  lines.push(
    `| ${t.id} | ${t.category} | \`${t.slug}\` | ${isImpl ? 'completed' : 'planned'} | ${
      isImpl ? 'available' : 'unavailable'
    } | ${t.restricted ? 'yes' : 'no'} | ${isImpl ? 'PASS' : 'NOT RUN'} |`
  );
}
lines.push('');
lines.push('## Cross-cutting requirements');
lines.push('');
lines.push('| Requirement | Status | Evidence |');
lines.push('|---|---|---|');
const cross = [
  ['Registry integrity validation', existsSync(join(ROOT, 'lib/tools/validation.ts')) ? 'PASS' : 'FAIL', 'tests/unit/validateTools.test.ts'],
  ['Canonical hierarchical routing', existsSync(join(ROOT, 'app/smarttools/[category]/[tool]/page.tsx')) ? 'PASS' : 'FAIL', 'app/smarttools/[category]/[tool]/page.tsx'],
  ['Bilingual search (AR/EN)', existsSync(join(ROOT, 'lib/tools/search.ts')) ? 'PASS' : 'FAIL', 'lib/tools/search.ts'],
  ['AI assistant (fallback verified)', existsSync(join(ROOT, 'lib/ai/service.ts')) ? 'PARTIAL' : 'FAIL', 'lib/ai/ai.test.ts (provider NOT RUN without credentials)'],
  ['AI provider (real model)', 'NOT RUN', 'requires AI_PROVIDER_URL + AI_PROVIDER_API_KEY'],
  ['Supabase RLS for AI memory', 'BLOCKED', 'pending migration + approval (production DB protection)'],
];
for (const [name, status, evidence] of cross) lines.push(`| ${name} | ${status} | ${evidence} |`);
lines.push('');

const out = join(ROOT, 'docs/smarttools/TRACEABILITY_MATRIX.md');
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${out} (${catalog.length} implemented, ${registered.length} registered)`);
