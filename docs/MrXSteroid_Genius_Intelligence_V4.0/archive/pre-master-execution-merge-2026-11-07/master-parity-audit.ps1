# Normalize only presentation variants: case, dash style, multiplication sign
# and whitespace. No wording is added, removed or reordered by this step.
function Normalize([string]$s) {
  if ($null -eq $s) { return '' }
  $s = $s.Replace([string][char]0x2014, '-').Replace([string][char]0x2013, '-').Replace([string][char]0x00D7, 'x')
  $s = [regex]::Replace($s, '\s+', ' ')
  return $s.ToLowerInvariant().Trim()
}
