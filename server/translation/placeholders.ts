import type { TranslationGlossaryTerm } from './glossary';

/** Strict, identity-bearing marker. Restoration never relies on token order. */
export const SENTINEL_PATTERN = /__MRX_TOKEN_(\d+)__/g;
const SENTINEL_FRAGMENT = /_*MRX_TOKEN_[A-Za-z0-9]*_*/g;

export type ProtectedValueKind =
    | 'glossary'
    | 'url'
    | 'email'
    | 'template'
    | 'html'
    | 'currency'
    | 'identifier'
    | 'number';

export type ProtectedValue = {
    readonly id: number;
    readonly token: string;
    readonly original: string;
    readonly replacement: string;
    readonly kind: ProtectedValueKind;
};

export type ProtectedTranslation = {
    readonly sourceText: string;
    readonly protectedText: string;
    readonly values: readonly ProtectedValue[];
};

export type SentinelValidationError =
    | 'MISSING_TOKEN'
    | 'DUPLICATE_TOKEN'
    | 'UNKNOWN_TOKEN'
    | 'MALFORMED_TOKEN';

export type SentinelRestorationResult =
    | { readonly ok: true; readonly text: string }
    | { readonly ok: false; readonly code: SentinelValidationError };

type Candidate = {
    start: number;
    end: number;
    original: string;
    replacement: string;
    kind: ProtectedValueKind;
    priority: number;
};

const PATTERNS: readonly { kind: ProtectedValueKind; priority: number; regex: RegExp }[] = [
    { kind: 'url', priority: 100, regex: /\b(?:https?:\/\/|www\.)[^\s<>{}[\]]+/gi },
    { kind: 'email', priority: 95, regex: /\b[A-Z0-9._%+-]+@[A-Z0-9.-]+\.[A-Z]{2,}\b/gi },
    { kind: 'template', priority: 90, regex: /\{\{[^{}\r\n]+}}|\$\{[^{}\r\n]+}|\{[A-Za-z_][\w.-]*}/g },
    { kind: 'html', priority: 85, regex: /<[^<>]+>/g },
    { kind: 'currency', priority: 80, regex: /(?:[$€£¥]\s?\d[\d,.]*|\b\d[\d,.]*\s?(?:USD|EUR|GBP|EGP|SAR|AED|JPY|CNY|RMB)\b)/gi },
    // Machine/business identifiers with separators or a label. Ordinary prose
    // words are intentionally excluded.
    { kind: 'identifier', priority: 70, regex: /\b(?:order|invoice|payment|intent|referral|affiliate|payout|coupon|wallet|transaction)\s*(?:#|ID\s*[:#-]?|code\s*[:#-]?)\s*[A-Z0-9][A-Z0-9_-]{2,}\b/gi },
    { kind: 'identifier', priority: 65, regex: /\b(?=[A-Z0-9_-]{6,}\b)(?=[A-Z0-9_-]*\d)(?=[A-Z0-9_-]*[-_])[A-Z0-9_-]+\b/g },
    { kind: 'number', priority: 10, regex: /(?<![\p{L}\p{N}_])[-+]?\d+(?:[.,]\d+)*(?:\s?%|\s?(?:kg|g|mg|mcg|lb|cm|mm|ml|L|oz|kcal))?(?![\p{L}\p{N}_])/giu },
];

function token(id: number): string {
    return `__MRX_TOKEN_${id}__`;
}

function collectRegexCandidates(text: string): Candidate[] {
    const candidates: Candidate[] = [];
    for (const pattern of PATTERNS) {
        pattern.regex.lastIndex = 0;
        for (const match of text.matchAll(pattern.regex)) {
            if (match.index === undefined || match[0] === '') continue;
            candidates.push({
                start: match.index,
                end: match.index + match[0].length,
                original: match[0],
                replacement: match[0],
                kind: pattern.kind,
                priority: pattern.priority,
            });
        }
    }
    return candidates;
}

function collectGlossaryCandidates(text: string, terms: readonly TranslationGlossaryTerm[]): Candidate[] {
    const candidates: Candidate[] = [];
    for (const term of terms) {
        if (term.source === '') continue;
        let from = 0;
        while (from <= text.length) {
            const start = text.indexOf(term.source, from);
            if (start < 0) break;
            candidates.push({
                start,
                end: start + term.source.length,
                original: term.source,
                replacement: term.replacement,
                kind: 'glossary',
                priority: 110,
            });
            from = start + term.source.length;
        }
    }
    return candidates;
}

function selectNonOverlapping(candidates: Candidate[]): Candidate[] {
    const selected: Candidate[] = [];
    const sorted = [...candidates].sort(
        (a, b) => a.start - b.start || b.priority - a.priority || (b.end - b.start) - (a.end - a.start)
    );
    for (const candidate of sorted) {
        if (selected.some((entry) => candidate.start < entry.end && candidate.end > entry.start)) continue;
        selected.push(candidate);
    }
    return selected.sort((a, b) => a.start - b.start);
}

export function protectTranslationValues(
    sourceText: string,
    glossaryTerms: readonly TranslationGlossaryTerm[] = []
): ProtectedTranslation {
    // Existing marker-shaped source content is itself protected; it must never
    // be confused with markers generated by this invocation.
    const existing = new RegExp(SENTINEL_PATTERN.source, SENTINEL_PATTERN.flags);
    const sourceWithEscapedMarkers = sourceText.replace(existing, (value) => value.replace(/_/g, '＿'));
    const selected = selectNonOverlapping([
        ...collectGlossaryCandidates(sourceWithEscapedMarkers, glossaryTerms),
        ...collectRegexCandidates(sourceWithEscapedMarkers),
    ]);

    const values: ProtectedValue[] = [];
    let cursor = 0;
    let protectedText = '';
    for (const candidate of selected) {
        protectedText += sourceWithEscapedMarkers.slice(cursor, candidate.start);
        const id = values.length;
        const marker = token(id);
        protectedText += marker;
        values.push({
            id,
            token: marker,
            original: candidate.original.replace(/＿/g, '_'),
            replacement: candidate.replacement.replace(/＿/g, '_'),
            kind: candidate.kind,
        });
        cursor = candidate.end;
    }
    protectedText += sourceWithEscapedMarkers.slice(cursor);

    return { sourceText, protectedText, values };
}

function hasMalformedSentinelFragment(text: string, validSpans: ReadonlySet<string>): boolean {
    for (const match of text.matchAll(new RegExp(SENTINEL_FRAGMENT.source, SENTINEL_FRAGMENT.flags))) {
        if (!validSpans.has(match[0])) return true;
    }
    return false;
}

export function validateAndRestoreTranslation(
    translatedText: string,
    protection: ProtectedTranslation
): SentinelRestorationResult {
    const expected = new Map(protection.values.map((value) => [value.id, value]));
    const counts = new Map<number, number>();
    const foundTokens = new Set<string>();

    for (const match of translatedText.matchAll(new RegExp(SENTINEL_PATTERN.source, SENTINEL_PATTERN.flags))) {
        const id = Number(match[1]);
        foundTokens.add(match[0]);
        if (!expected.has(id)) return { ok: false, code: 'UNKNOWN_TOKEN' };
        counts.set(id, (counts.get(id) ?? 0) + 1);
    }

    if (hasMalformedSentinelFragment(translatedText, foundTokens)) {
        return { ok: false, code: 'MALFORMED_TOKEN' };
    }

    for (const value of protection.values) {
        const count = counts.get(value.id) ?? 0;
        if (count === 0) return { ok: false, code: 'MISSING_TOKEN' };
        if (count !== 1) return { ok: false, code: 'DUPLICATE_TOKEN' };
    }

    const text = translatedText
        .replace(
            new RegExp(SENTINEL_PATTERN.source, SENTINEL_PATTERN.flags),
            (_marker, rawId: string) => expected.get(Number(rawId))!.replacement
        )
        .replace(/＿/g, '_');
    return { ok: true, text };
}
